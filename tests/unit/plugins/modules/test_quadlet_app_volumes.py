"""Volume ownership: X-Owner parsing and validation, the generated bootstrap unit, marker cleanup."""

import os

import pytest

from ansible_collections.kriansa.commons.plugins.modules.quadlet_app import (
    QuadletAppModule,
    ValidationError,
)
from ansible_collections.kriansa.commons.tests.unit._support.fakes import (
    AnsibleFailJson,
    FakeModule,
    raiser,
)


def make_module(name="app"):
    module = QuadletAppModule(
        FakeModule(
            {
                "src": f"/apps/{name}",
                "name": None,
                "state": "started",
                "force": False,
                "systemctl_timeout": 120,
                "_control_node_processed": True,
                "_files_data": None,
            }
        )
    )
    return module


class TestCollectVolumeOwners:
    def collect(self, files):
        return make_module()._collect_volume_owners(files)

    def test_only_volumes_get_an_owner_and_it_defaults_to_root(self):
        files = {
            "data.volume": "[Volume]\nDriver=local\n",
            "main.container": "[Container]\nX-Owner=1:1\n",
            "main.network": "[Network]\n",
        }
        assert self.collect(files) == {"data": "0:0"}

    def test_declared_owner(self):
        assert self.collect({"data.volume": "[Volume]\nX-Owner=1000:1000\n"}) == {"data": "1000:1000"}

    def test_every_volume_is_listed(self):
        files = {"a.volume": "[Volume]\nX-Owner=1:1\n", "b.volume": "[Volume]\n"}
        assert self.collect(files) == {"a": "1:1", "b": "0:0"}

    def test_last_declaration_wins(self):
        # Pinned
        assert self.collect({"d.volume": "[Volume]\nX-Owner=1:1\nX-Owner=2:2\n"}) == {"d": "2:2"}

    @pytest.mark.parametrize(
        "line, expected",
        [
            ("  X-Owner=5:5", "5:5"),
            ("X-Owner= 5:5 ", "5:5"),
            ("# X-Owner=5:5", "0:0"),
            # Pinned: with a space before "=" the directive is not recognised and the volume
            # silently falls back to root
            ("X-Owner = 5:5", "0:0"),
        ],
    )
    def test_line_forms(self, line, expected):
        assert self.collect({"d.volume": f"[Volume]\n{line}\n"}) == {"d": expected}

    def test_any_section_counts(self):
        assert self.collect({"d.volume": "[Unit]\nX-Owner=7:7\n[Volume]\n"}) == {"d": "7:7"}

    def test_invalid_owner_names_the_file(self):
        with pytest.raises(ValidationError, match="Invalid X-Owner in d.volume"):
            self.collect({"d.volume": "[Volume]\nX-Owner=abc\n"})


class TestValidateOwner:
    @pytest.mark.parametrize("value", ["0:0", "1000:1000", "65535:65535", "0:65535"])
    def test_accepted(self, value):
        assert QuadletAppModule._validate_owner(value, "d.volume") == value

    def test_leading_zeros_are_kept(self):
        # Pinned: not normalised, so the marker path carries the zeros too
        assert QuadletAppModule._validate_owner("001:002", "d.volume") == "001:002"

    def test_non_ascii_digits_are_accepted(self):
        # Pinned: str.isdigit() accepts them, and int() parses them
        assert QuadletAppModule._validate_owner("١٠:١٠", "d.volume") == "١٠:١٠"

    @pytest.mark.parametrize(
        "value", ["", "a:b", "1000", "1:2:3", "-1:0", "+1:1", "1000:", ":1000", "1: 1", "1.0:1"]
    )
    def test_malformed(self, value):
        with pytest.raises(ValidationError) as excinfo:
            QuadletAppModule._validate_owner(value, "d.volume")
        assert str(excinfo.value) == (
            f"Invalid X-Owner in d.volume: '{value}'. "
            "Expected a numeric uid:gid pair, for example X-Owner=10000:10000"
        )

    @pytest.mark.parametrize("value", ["65536:0", "0:65536", "100000:100000"])
    def test_out_of_range(self, value):
        with pytest.raises(ValidationError) as excinfo:
            QuadletAppModule._validate_owner(value, "d.volume")
        assert str(excinfo.value) == (
            f"X-Owner in d.volume is out of range: '{value}'. Ids must be below 65536, which is "
            "the size of the user namespace the consuming container gets. A higher id would be "
            "written to disk and then be invisible to the app that needs it."
        )


